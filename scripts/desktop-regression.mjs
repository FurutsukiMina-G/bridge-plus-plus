import assert from 'node:assert/strict';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {KimiAcpAdapter} from '../app/runtimes/kimi-acp.mjs';

/** Real renderer and IPC checks, isolated files; no agent inference. */
export async function runRegression({window,methods,store,capture}){
  const js=code=>window.webContents.executeJavaScript(code,true),pause=()=>new Promise(r=>setTimeout(r,60));
  const until=async check=>{for(let n=0;n<150;n++){if(await check())return;await pause();}throw new Error('Desktop condition timed out');};
  const click=async selector=>{await js(`document.querySelector(${JSON.stringify(selector)}).click()`);await pause();};
  const input=async(selector,text)=>{await js(`{const el=document.querySelector(${JSON.stringify(selector)});el.value=${JSON.stringify(text)};el.dispatchEvent(new Event('input',{bubbles:true}));}`);};
  const exists=selector=>js(`!!document.querySelector(${JSON.stringify(selector)})`);
  const escape=()=>js('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape"}))');
  const projects=['a','b'].map(id=>({id:'qa-'+id,name:'QA '+id.toUpperCase(),path:resolve('.runtime/desktop-fixtures/'+id),createdAt:new Date().toISOString()}));
  for(const p of projects){await mkdir(p.path,{recursive:true});await writeFile(join(p.path,'sample.txt'),p.name);}
  const session={id:'qa-stream',projectId:'qa-a',runtimeId:'codex',selection:{modelKey:'native'},title:'流式显示检查',status:'idle',createdAt:new Date().toISOString(),updatedAt:new Date().toISOString()};
  await store.mutate(s=>{s.projects=projects;s.sessions=[session];});
  const openFile=async()=>{await until(()=>exists('[data-file-path="sample.txt"]'));await click('[data-file-path="sample.txt"]');await until(async()=>await exists('#edit-file')||await exists('#editor'));if(await exists('#edit-file'))await click('#edit-file');await until(()=>exists('#editor'));};
  try{
    await until(()=>exists('[data-new-in="qa-a"]'));
    await click('[data-new-in="qa-a"]');await input('#prompt','甲项目草稿');
    await click('[data-new-in="qa-b"]');await input('#prompt','乙项目草稿');
    await click('[data-new-in="qa-a"]');
    assert.equal(await js('document.querySelector("#prompt").value'),'甲项目草稿');
    await click('[data-rtab="files"]');await openFile();
    await input('#editor','甲项目未保存编辑');
    await click('[data-new-in="qa-b"]');await openFile();
    assert.equal(await js('document.querySelector("#editor").value'),'QA B');
    await input('#editor','乙项目未保存编辑');
    await click('[data-new-in="qa-a"]');await until(()=>exists('#editor'));
    assert.equal(await js('document.querySelector("#editor").value'),'甲项目未保存编辑');
    await click('#save-file');
    await until(async()=>await readFile(join(projects[0].path,'sample.txt'),'utf8')==='甲项目未保存编辑');
    assert.equal(await readFile(join(projects[1].path,'sample.txt'),'utf8'),'QA B');
    await capture('10-preserved-editor');
    await click('[data-new-in="qa-b"]');await until(()=>exists('#editor'));
    assert.equal(await js('document.querySelector("#editor").value'),'乙项目未保存编辑');
    await click('#save-file');
    await until(async()=>await readFile(join(projects[1].path,'sample.txt'),'utf8')==='乙项目未保存编辑');
    await click('[data-new-in="qa-a"]');await click('[data-rtab="tasks"]');
    await methods['terminal:run']({projectId:'qa-a',command:'Start-Sleep -Milliseconds 300; [Console]::WriteLine("终端甲✓")'});
    await click('[data-new-in="qa-b"]');
    await methods['terminal:run']({projectId:'qa-b',command:'[Console]::WriteLine("终端乙✓")'});
    await until(async()=>!(await methods['terminal:state']({projectId:'qa-a'})).running&&!(await methods['terminal:state']({projectId:'qa-b'})).running);
    await until(async()=>/终端乙✓/.test(await js('document.querySelector("#terminal-output").textContent')));
    assert.doesNotMatch(await js('document.querySelector("#terminal-output").textContent'),/终端甲✓/);
    await click('[data-new-in="qa-a"]');
    assert.match(await js('document.querySelector("#terminal-output").textContent'),/终端甲✓/);
    assert.equal(await js('document.querySelector("#terminal-command").disabled'),false);
    await capture('11-isolated-terminal');
    await click('[data-session="qa-stream"]');
    assert.ok(await js('document.querySelector("#env-chip .icon").getBoundingClientRect().height<=20'));
    assert.ok(await js('document.querySelector("#scroller").getBoundingClientRect().height>200'));
    assert.ok(await js('document.querySelector("#send").getBoundingClientRect().bottom<innerHeight'));
    assert.ok(await js('document.querySelector("#context-ring .ring").getBoundingClientRect().bottom<=innerHeight'));
    const label=()=>js('document.querySelector(".working-label")?.textContent??null'),userBlock=JSON.stringify('#chat [data-key^="user:"]');
    await store.mutate(()=>{session.status='running';});
    await store.event(session.id,{type:'user',text:'流式检查'});
    await until(()=>exists('#chat [data-key^="user:"]'));
    await until(async()=>await label()==='等待模型响应');
    await js(`window.qaUserBlock=document.querySelector(${userBlock})`);
    for(let i=0;i<12;i++){await store.event(session.id,{type:'text',text:'流式片段 ',turnId:'qa-turn'});await pause();if(i===5)assert.match(await js('document.querySelector("#chat").textContent'),/流式片段/);}
    assert.equal(await js('document.querySelectorAll(".message:not(.user-message)").length'),1);
    await until(async()=>await label()==='正在输出回复');
    // Streaming patches the transcript in place: the sent message is never recreated, so its entrance animation cannot replay.
    assert.equal(await js(`window.qaUserBlock===document.querySelector(${userBlock})`),true);
    await store.event(session.id,{type:'tool-start',name:'本地检查工具',toolId:'qa-tool',data:{fixture:true}});
    await until(()=>exists('details.tool'));
    await until(async()=>await label()==='正在调用工具');
    assert.equal(await js('document.querySelector(".working-detail")?.textContent'),'本地检查工具');
    assert.equal(await js('document.querySelector(".footer-status")?.textContent'),'正在调用工具');
    await js('document.querySelector("details.tool").open=true');
    await store.event(session.id,{type:'notice',text:'测试过程中保留工具详情展开状态'});
    await pause();await pause();
    assert.equal(await js('document.querySelector("details.tool").open'),true);
    await store.event(session.id,{type:'usage',scope:'request',source:'gateway',turnId:'qa-turn',data:{prompt_tokens:20000,completion_tokens:0,cached_tokens:15000,cache_status:'reported',context_window:200000,first_token_ms:200,duration_ms:1200}});
    await until(async()=>/缓存命中 75%/.test(await js('document.querySelector("#composer-footer").textContent')));
    assert.match(await js('document.querySelector("#context-ring").textContent'),/10%/);
    await store.event(session.id,{type:'turn-end',status:'completed',turnId:'qa-turn'});
    await store.mutate(()=>{session.status='completed';});
    await until(async()=>!await exists('.working'));
    assert.equal(await js(`window.qaUserBlock===document.querySelector(${userBlock})`),true);
    await capture('12-streaming-chat');
    const permissionSession={...session,id:'qa-permissions',runtimeId:'kimi',title:'原生授权重启检查',status:'waiting'};
    await store.mutate(s=>{s.sessions.push(permissionSession);});
    await store.event(permissionSession.id,{type:'user',text:'本机授权恢复检查'});
    const options=[{kind:'allow_once',optionId:'once'},{kind:'allow_always',optionId:'session'},{kind:'reject_once',optionId:'reject'}];
    const request={id:0,method:'session/request_permission',params:{sessionId:'qa-child',options,toolCall:{title:'Bash',toolCallId:'qa-shell'}}};
    // Reproduce the old durable-ID collision in the actual unchanged renderer.
    await store.event(permissionSession.id,{type:'approval',approvalId:'kimi:0',name:'Bash',choices:['approve','approve-session','reject'],data:request.params});
    await store.event(permissionSession.id,{type:'approval-resolved',approvalId:'kimi:0',choice:'approve'});
    await store.event(permissionSession.id,{type:'approval',approvalId:'kimi:0',name:'Bash',choices:['approve','approve-session','reject'],data:request.params});
    await until(()=>exists('[data-session="qa-permissions"]'));await click('[data-session="qa-permissions"]');await until(async()=>/授权已允许/.test(await js('document.querySelector("#chat").textContent')));
    assert.equal(await js('document.querySelectorAll("#chat [data-approval]").length'),0);
    await store.event(permissionSession.id,{type:'approval-resolved',approvalId:'kimi:0',choice:'expired'});
    let fresh;const adapter=new KimiAcpAdapter({emit:async e=>{fresh=e;await store.event(permissionSession.id,e);}});await adapter.message(request);
    assert.notEqual(fresh.approvalId,'kimi:0');
    await until(async()=>await js('document.querySelectorAll("#chat [data-approval]").length')===3);
    assert.deepEqual(await js('[...document.querySelectorAll("#chat [data-approval]")].map(e=>e.dataset.approval)'),Array(3).fill(fresh.approvalId));
    await window.webContents.reload();await until(()=>exists('[data-session="qa-permissions"]'));await click('[data-session="qa-permissions"]');await until(async()=>await js('document.querySelectorAll("#chat [data-approval]").length')===3);
    assert.deepEqual(await js('[...document.querySelectorAll("#chat [data-approval]")].map(e=>e.dataset.approval)'),Array(3).fill(fresh.approvalId));
    await capture('16-approval-restart');
    await store.event(permissionSession.id,{type:'approval-resolved',approvalId:fresh.approvalId,choice:'expired'});await store.mutate(()=>{permissionSession.status='interrupted';});
    const qoderModel=Object.values(store.state.catalog).flatMap(c=>c.models??[]).find(m=>m.source==='qoder'&&m.enabled&&m.contexts.length);assert.ok(qoderModel);
    const cacheSession={...session,id:'qa-cache',runtimeId:'kimi',title:'缓存来源检查',status:'completed',selection:{modelKey:qoderModel.key,identity:qoderModel.identity,contextTokens:qoderModel.contexts[0].tokens,reasoning:qoderModel.reasoning[0]}};
    await store.mutate(s=>{s.sessions.push(cacheSession);});await store.event(cacheSession.id,{type:'user',text:'缓存来源检查'});
    for(const cached of [900,1990])await store.event(cacheSession.id,{type:'usage',scope:'request',source:'gateway',turnId:'qa-cache-turn',data:{prompt_tokens:1000,completion_tokens:10,cached_tokens:cached,cache_status:'estimated',context_window:200000}});
    await until(()=>exists('[data-session="qa-cache"]'));await click('[data-session="qa-cache"]');
    await until(async()=>/缓存命中\s*未报告/.test(await js('document.querySelector("#composer-footer").textContent')));
    assert.doesNotMatch(await js('document.querySelector("#composer-footer").textContent'),/199%|90%/);await capture('17-cache-provenance');
    const projected=await methods['session:events']({sessionId:cacheSession.id});assert.ok(projected.filter(e=>e.type==='usage').every(e=>e.data.cached_tokens===null));
    assert.equal((await store.events(cacheSession.id)).find(e=>e.data?.cached_tokens===1990).data.cached_tokens,1990,'Original diagnostics must not be overwritten');
    await store.event(cacheSession.id,{type:'usage',scope:'request',source:'gateway',data:{prompt_tokens:1000,completion_tokens:10,cached_tokens:750,cache_status:'reported',context_window:200000}});
    await until(async()=>/缓存命中 75%/.test(await js('document.querySelector("#composer-footer").textContent')));
    const model=Object.values(store.state.catalog).flatMap(c=>c.models??[]).find(m=>m.source==='workbuddy'&&m.enabled&&m.contexts.length);
    assert.ok(model);
    const recovery={...session,id:'qa-rebind',title:'模型更新恢复检查',nativeId:'qa-native-preserved',selection:{modelKey:model.key,identity:'stale-identity',contextTokens:model.contexts[0].tokens,reasoning:model.reasoning[0]}};
    await store.mutate(s=>{s.sessions.push(recovery);});
    await store.event(recovery.id,{type:'user',text:'确认后应保留的历史'});
    await until(()=>exists('[data-session="qa-rebind"]'));
    await click('[data-session="qa-rebind"]');
    await until(()=>exists('#rebind-session-model'));
    await input('#prompt','恢复后继续发送的草稿');
    await click('#send');
    assert.equal(await js('document.querySelector("#prompt").value'),'恢复后继续发送的草稿');
    assert.equal((await store.events(recovery.id)).filter(e=>e.type==='user').length,1);
    await click('#rebind-session-model');
    assert.match(await js('document.querySelector("#modal").textContent'),new RegExp(model.id));
    await capture('13-model-reconfirmation');
    await click('#modal-confirm');
    await until(()=>recovery.selection.identity===model.identity);
    assert.equal(recovery.nativeId,'qa-native-preserved');
    assert.equal(recovery.runtimeId,'codex');
    await until(async()=>!await exists('#session-model-warning'));
    assert.match(await js('document.querySelector("#chat").textContent'),/确认后应保留的历史/);
    assert.equal(await js('document.querySelector("#prompt").value'),'恢复后继续发送的草稿');
    await capture('14-model-recovered');
    const pickEnv=async id=>{await click('#env-chip');await click(`[data-env="${id}"]`);};
    const nativeMenu=async()=>{await click('#model-chip');if(await js('document.querySelector("#model-chip").dataset.value')!=='native')await click('[data-model-key="native"]');await until(()=>exists('#native-id'));};
    await click('#new-session');
    await pickEnv('codex');await nativeMenu();
    await input('#native-id','qa-native-codex');
    await click('#save-model-default');
    await until(()=>store.state.preferences.modelDefaults['native:codex']?.nativeModel==='qa-native-codex');
    await escape();await pickEnv('kimi');await nativeMenu();
    assert.equal(await js('document.querySelector("#native-id").value'),'');
    await escape();await pickEnv('codex');await nativeMenu();
    assert.equal(await js('document.querySelector("#native-id").value'),'qa-native-codex');
    await escape();
    await window.webContents.reload();
    await until(()=>exists('[data-rtab="tasks"]'));
    await click('[data-rtab="tasks"]');
    await until(async()=>/终端甲✓/.test(await js('document.querySelector("#terminal-output")?.textContent??""')));
    assert.equal(await js('document.querySelector("#terminal-command").disabled'),false);
    return {projectDrafts:true,unsavedEditors:true,saveTargets:true,terminalIsolation:true,terminalUnicode:true,terminalReload:true,incrementalRendering:true,stableStreamingBlocks:true,liveActivity:true,toolDetailsPreserved:true,sessionLayout:true,footerMetrics:true,nativeDefaultsSeparated:true,modelRecovery:true,legacyApprovalCollisionReproduced:true,freshApprovalVisible:true,pendingApprovalSurvivesReload:true,cacheProvenance:true,invalidCacheHiddenWithoutJournalRewrite:true};
  }catch(error){
    await capture('regression-failure');
    await writeFile(resolve('.runtime/desktop-artifacts/failure.txt'),await js('document.body.innerText'));
    throw error;
  }finally{
    await methods['editor:dirty']({dirty:false});
  }
}
