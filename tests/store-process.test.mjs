test('workspace groups pending writes, acknowledges both copies and keeps journal ordering',async t=>{
  const root=await mkdtemp(join(tmpdir(),'awb-state-batch-'));
  const store=await new Store(root).open();
  t.after(async()=>{await store.close();await rm(root,{recursive:true,force:true});});
  await store.mutate(state=>state.sessions.push({id:'batched'}));
  const wrote=[],write=store.writeSnapshot.bind(store);
  store.writeSnapshot=async(file,content)=>{await write(file,content);wrote.push(JSON.parse(content).sessions[0].nativeId);};
  const first=store.mutate(state=>{state.sessions[0].nativeId='first';});
  const second=store.mutate(state=>{state.sessions[0].nativeId='second';});
  const journal=store.enqueue(async()=>assert.equal(JSON.parse(await readFile(store.file,'utf8')).sessions[0].nativeId,'second'));
  const third=store.mutate(state=>{state.sessions[0].nativeId='third';});
  await Promise.all([first,second,journal,third]);
  assert.deepEqual(wrote,['second','second','third','third']);
  assert.equal(await readFile(store.file,'utf8'),await readFile(store.backupFile,'utf8'));
  await store.save();
  assert.equal(wrote.length,4);
  await assert.rejects(store.mutate(state=>{state.sessions=[];}),/populated session index/);
  assert.equal(JSON.parse(await readFile(store.file,'utf8')).sessions[0].nativeId,'third');
});
test('a partially failed workspace batch rejects each caller and retries both copies',async t=>{
  const root=await mkdtemp(join(tmpdir(),'awb-state-retry-'));
  const store=await new Store(root).open();
  t.after(async()=>{await store.close();await rm(root,{recursive:true,force:true});});
  const original=await readFile(store.file,'utf8'),write=store.writeSnapshot.bind(store);
  store.writeSnapshot=async(file,content)=>{
    if(file===store.file)throw new Error('synthetic write failure');
    await write(file,content);
  };
  const calls=[store.mutate(state=>{state.preferences.theme='light';}),store.save()];
  for(const call of calls)await assert.rejects(call,/synthetic write failure/);
  assert.equal(await readFile(store.file,'utf8'),original);
  assert.notEqual(await readFile(store.backupFile,'utf8'),original);
  store.writeSnapshot=write;
  await store.mutate(state=>{state.preferences.theme='dark';});
  assert.equal(await readFile(store.file,'utf8'),original);
  assert.equal(await readFile(store.backupFile,'utf8'),original);
});
